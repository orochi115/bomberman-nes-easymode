  JSR QUEUE_TILE_Y2
  DEC TEMP4
  BNE TRY_SOFT_CELL
  JSR PLACE_BOMB_PICKUPS
  JSR LOAD_ENEMIES
  JMP OPEN_PLACEMENT_CELLS

