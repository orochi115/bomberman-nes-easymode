; Spawn the stage enemies. Z_4E places eight type-0 enemies on FIXED_SPAWN_COL/ROW. Z_49 nonzero returns. Otherwise LOAD_SPAWN_LIST and place each type until a negative byte.
.SPAWN_STAGE_ENEMIES
  ABS_LDA Z_4E
  BNE L0_8066
  ABS_LDY Z_49
  BNE L0_8020
  JSR LOAD_SPAWN_LIST
  LDY #&00
  STY Z_2A
.L0_8011
  LDY Z_2A
  LDA (Z_20),Y
  BMI L0_801F
  JSR SPAWN_ENEMY_ON_EMPTY
  INC Z_2A
  JMP L0_8011
.L0_801F
  RTS
.L0_8020
  RTS

; A is the enemy type. Random column Z_28 is 0-31. Row comes from SPAWN_ROW_PICK. Rows under 5 need column at least 5. Map cell must be 0. Then PLACE_ENEMY.
.SPAWN_ENEMY_ON_EMPTY
  STA X_62E1
.L0_8024
  JSR NEXT_RNG
  AND #&1F
  STA Z_28
  JSR NEXT_RNG
  AND #&0F
  TAX
  LDY SPAWN_ROW_PICK,X
  STY Z_29
  CPY #&05
  BCS L0_8040
  LDA Z_28
  CMP #&05
  BCC L0_8024
.L0_8040
  LDA MAP_ROW_LO,Y
  STA Z_2F
  LDA MAP_ROW_HI,Y
  STA Z_30
  LDY Z_28
  LDA (Z_2F),Y
  BNE L0_8024
  LDA X_62E1
  JMP PLACE_ENEMY

